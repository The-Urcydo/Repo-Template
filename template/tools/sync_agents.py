#!/usr/bin/env python3
"""Generate tool-specific adapters from the tool-neutral harness in agents/.

Source of truth:  agents/roles/<role>/ROLE.md, agents/skills/*/ (shared skills),
                  agents/roles/<role>/skills/*/ (skills only that role uses), every AGENTS.md
Generated for Claude Code (when enabled in agents/adapters/targets.json):
  .claude/agents/<role>.md        subagent definitions (name + description + charter; plus `model` and
                                  `disallowedTools` when targets.json maps them, see adapters/README.md)
  .claude/skills/<name>/...       copies of the open-standard skill folders (flat, from both lanes)
  <dir>/CLAUDE.md                 one-line shim importing the sibling AGENTS.md
                                  (Claude Code reads CLAUDE.md instead of AGENTS.md
                                  when both exist, so each AGENTS.md needs a shim)
Generated for Cursor (optional, disabled by default):
  .cursor/rules/00-repo.mdc       short always-on pointer to AGENTS.md (no copy of it)
  .cursor/rules/role-<role>.mdc   one agent-requested rule per role charter
Generated for GitHub Copilot (optional, disabled by default):
  .github/copilot-instructions.md short pointer to AGENTS.md (no copy of it)
Generated for Gemini CLI (optional, disabled by default):
  .gemini/settings.json           configures context.fileName to read AGENTS.md
Everything generated is recorded in agents/adapters/manifest.json. Never edit
generated files by hand; edit the source and re-run this tool.

Other agent tools (Codex, DeepSeek-based agents, ...) read AGENTS.md and the plain
files in agents/ directly. To add a target, extend targets.json and this file.

Usage: python3 tools/sync_agents.py [--check]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lib import (  # noqa: E402
    SKIP_DIRS, TOOL_NAME_RE, folder_owners, load_roles, load_targets, read_text, repo_root, sha256_bytes,
    skill_folders, write_text, yaml_scalar,
)

MANIFEST = "agents/adapters/manifest.json"
SHIM = "@AGENTS.md\n"
# Pointers, not copies: the tool reads AGENTS.md itself, so copying it would load the same text twice.
CURSOR_POINTER = (
    "---\n"
    "description: Entry point for this repository's agent harness\n"
    "alwaysApply: true\n"
    "---\n"
    "Read `AGENTS.md` at the repository root first: it holds the commands, rules and role dispatch.\n"
    "Role charters are the `role-*` rules (source: `agents/roles/`); shared protocols are in `agents/protocols/`.\n"
    "\n"
    "> Generated by `tools/sync_agents.py`. Do not edit.\n"
)
COPILOT_POINTER = (
    "<!-- Generated by tools/sync_agents.py. Do not edit. -->\n"
    "Read `AGENTS.md` at the repository root first: it holds the commands, rules and role dispatch.\n"
    "The documentation index is `docs/INDEX.md`; role charters, protocols and skills are in `agents/`.\n"
)
GEMINI_SETTINGS = (
    json.dumps({"context": {"fileName": ["AGENTS.md", "GEMINI.md"]}}, indent=2) + "\n"
)


def _agents_md_dirs(root: Path) -> list[Path]:
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not (
            Path(dirpath).relative_to(root).parts[:1] == ("work",) and d in ("archive", ".locks")))
        if "AGENTS.md" in filenames:
            found.append(Path(dirpath))
    return found


def _role_description(role: str, fm: dict) -> str:
    """The mission plus when to pick this role. A charter's `use_when` says it; without one the role is
    picked when it owns the item (flow roles). A role that is called, not handed an item, sets `use_when`."""
    mission = " ".join(str(fm.get("mission", "")).split())
    when = fm.get("use_when")
    if isinstance(when, str) and when.strip():
        return f"{mission} Use when {' '.join(when.split()).rstrip('. ')}."
    return f"{mission} Use when a work item's handoff owner_role is {role}."


def _claude_extra_head(role: str, fm: dict, cfg: dict) -> list[str]:
    """Optional subagent front matter lines: `model` (from `models` in targets.json) and `disallowedTools`
    (the charter's `access` looked up in `disallowed_tools`). Config that check.py would reject adds
    nothing, so a bad targets.json never crashes the sync."""
    lines: list[str] = []
    models = cfg.get("models")
    model = models.get(role) if isinstance(models, dict) else None
    if isinstance(model, str) and model.strip():
        lines.append(f"model: {yaml_scalar(model.strip())}")
    level = fm.get("access")
    table = cfg.get("disallowed_tools")
    tools = table.get(level) if isinstance(table, dict) and isinstance(level, str) else None
    if isinstance(tools, list) and tools and all(isinstance(t, str) and TOOL_NAME_RE.fullmatch(t) for t in tools):
        lines.append("disallowedTools: " + ", ".join(tools))  # the comma-separated form Claude Code documents
    return lines


def _role_brief(role: str, fm: dict, body: str, owned: list[str]) -> list[str]:
    """Lines of a role adapter after its front matter; every tool-specific adapter shares them."""

    def lst(key: str) -> str:
        v = fm.get(key) or []
        return ", ".join(str(x) for x in v) if isinstance(v, list) and v else "(none)"

    folders = ", ".join(owned + [str(f) for f in (fm.get("writes_files") or [])]) or "(none)"
    return [
        f"You are the **{role}** role for this repository.",
        "",
        f"Before acting, read `AGENTS.md`, your charter `agents/roles/{role}/ROLE.md`, and `agents/protocols/handoff.md`.",
        "",
        f"- Reads: {lst('reads')}",
        f"- Folders and files you exclusively own: {folders}",
        f"- Work-item files you exclusively write: {lst('item_files')}",
        f"- Never: {lst('never')}",
        f"- Done when: {fm.get('done_when', '')}",
        f"- Escalate when: {fm.get('escalate_when', '')}",
        "",
        body.strip(),
        "",
        f"> Generated from `agents/roles/{role}/ROLE.md` by `tools/sync_agents.py`. Do not edit.",
        "",
    ]


def render_subagent(role: str, fm: dict, body: str, owned: list[str], extra_head: list[str] | None = None) -> str:
    head = ["---", f"name: {role}", f"description: {yaml_scalar(_role_description(role, fm))}",
            *(extra_head or []), "---"]
    return "\n".join(head + _role_brief(role, fm, body, owned))


def render_cursor_rule(role: str, fm: dict, body: str, owned: list[str]) -> str:
    """An agent-requested rule: Cursor loads it when its description matches the task."""
    head = ["---", f"description: {yaml_scalar(_role_description(role, fm))}", "alwaysApply: false", "---"]
    return "\n".join(head + _role_brief(role, fm, body, owned))


def _role_files(root: Path) -> list[tuple[str, dict, str, list[str]]]:
    owners = folder_owners(root)
    return [
        (role, r["fm"], r["body"], [f"`{f}/`" for f, who in sorted(owners.items()) if who == role and f])
        for role, r in load_roles(root).items() if r["fm"]
    ]


def _claude_outputs(root: Path, cfg: dict) -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    agents_dir = cfg.get("agents_dir", ".claude/agents")
    skills_dir = cfg.get("skills_dir", ".claude/skills")
    for role, fm, body, owned in _role_files(root):
        out[f"{agents_dir}/{role}.md"] = render_subagent(
            role, fm, body, owned, _claude_extra_head(role, fm, cfg)).encode("utf-8")
    # Shared skills and role-only skills both land flat in `.claude/skills/<name>/`.
    for _owner, sk in skill_folders(root):
        if (sk / "SKILL.md").exists():
            for f in sorted(sk.rglob("*")):
                if f.is_file() and "__pycache__" not in f.parts:
                    out[f"{skills_dir}/{sk.name}/{f.relative_to(sk).as_posix()}"] = f.read_bytes()
    if cfg.get("claude_md_shims", True):
        for d in _agents_md_dirs(root):
            rel = (d / "CLAUDE.md").relative_to(root).as_posix()
            out[rel] = SHIM.encode("utf-8")
    return out


def _cursor_outputs(root: Path, cfg: dict) -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    rules_dir = cfg.get("rules_dir", ".cursor/rules")
    if (root / "AGENTS.md").exists():
        out[f"{rules_dir}/00-repo.mdc"] = CURSOR_POINTER.encode("utf-8")
    for role, fm, body, owned in _role_files(root):
        out[f"{rules_dir}/role-{role}.mdc"] = render_cursor_rule(role, fm, body, owned).encode("utf-8")
    return out


def _copilot_outputs(root: Path, cfg: dict) -> dict[str, bytes]:
    if not (root / "AGENTS.md").exists():
        return {}
    return {cfg.get("instructions_file", ".github/copilot-instructions.md"): COPILOT_POINTER.encode("utf-8")}


def _gemini_outputs(root: Path, cfg: dict) -> dict[str, bytes]:
    if not (root / "AGENTS.md").exists():
        return {}
    return {cfg.get("settings_file", ".gemini/settings.json"): GEMINI_SETTINGS.encode("utf-8")}


def expected_outputs(root: Path) -> dict[str, bytes]:
    """Map of repo-relative POSIX path -> bytes that the adapters should contain."""
    targets = load_targets(root)
    out: dict[str, bytes] = {}
    for name, build in (
        ("claude", _claude_outputs),
        ("cursor", _cursor_outputs),
        ("copilot", _copilot_outputs),
        ("gemini", _gemini_outputs),
    ):
        cfg = targets.get(name, {})
        if cfg.get("enabled"):
            out.update(build(root, cfg))
    return out


def manifest_for(files: dict[str, bytes]) -> str:
    data = {"generated_by": "tools/sync_agents.py", "files": {k: sha256_bytes(v) for k, v in sorted(files.items())}}
    return json.dumps(data, indent=2) + "\n"


def _previous_manifest(root: Path) -> dict[str, str]:
    p = root / MANIFEST
    if not p.exists():
        return {}
    try:
        return json.loads(read_text(p)).get("files", {})
    except (json.JSONDecodeError, OSError):
        return {}


def drift(root: Path) -> list[str]:
    """Human-readable list of differences between disk and what sync would write."""
    want = expected_outputs(root)
    problems = []
    for rel, data in sorted(want.items()):
        p = root / rel
        if not p.exists():
            problems.append(f"missing generated file: {rel}")
        elif p.read_bytes() != data:
            problems.append(f"generated file differs from its source: {rel}")
    for rel in sorted(set(_previous_manifest(root)) - set(want)):
        if (root / rel).exists():
            problems.append(f"stale generated file (source removed): {rel}")
    mp = root / MANIFEST
    if want or mp.exists():
        if not mp.exists() or read_text(mp) != manifest_for(want):
            problems.append(f"manifest out of date: {MANIFEST}")
    return problems


def sync(root: Path) -> list[str]:
    want = expected_outputs(root)
    prev = _previous_manifest(root)
    log: list[str] = []
    for rel, data in sorted(want.items()):
        p = root / rel
        if p.exists() and p.read_bytes() == data:
            continue
        if p.exists() and rel not in prev and p.read_bytes() != data:
            log.append(f"SKIPPED {rel}: exists and is not generated; move or delete it, then re-run")
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
        log.append(f"wrote {rel}")
    for rel in sorted(set(prev) - set(want)):
        p = root / rel
        if p.exists():
            p.unlink()
            log.append(f"removed {rel}")
            parent = p.parent
            while parent != root and parent.exists() and not any(parent.iterdir()):
                parent.rmdir()
                parent = parent.parent
    if want or (root / MANIFEST).exists():
        mp = root / MANIFEST
        content = manifest_for({k: v for k, v in want.items() if (root / k).exists() and (root / k).read_bytes() == v})
        if not mp.exists() or read_text(mp) != content:
            write_text(mp, content)
            log.append(f"wrote {MANIFEST}")
    return log


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if adapters are out of date")
    args = ap.parse_args(argv)
    root = repo_root()
    if args.check:
        problems = drift(root)
        for p in problems:
            print(p)
        return 1 if problems else 0
    log = sync(root)
    print("\n".join(log) if log else "adapters already up to date")
    return 1 if any(line.startswith("SKIPPED") for line in log) else 0


if __name__ == "__main__":
    sys.exit(main())

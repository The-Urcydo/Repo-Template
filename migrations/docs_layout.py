#!/usr/bin/env python3
"""Move a project's own docs from the v0.2.0 layout to the v0.3.0 layout (ADR 0008).

Before v0.3.0 the template put docs in docs/{explanation,how-to,reference,tutorials}/. Since v0.3.0 they live in
docs/dev/<same folder>/ (ADR 0006). Copier's 3-way merge moves the files the template ships; it cannot move the
files a project added itself, so they would stay behind in a folder the template no longer owns.

Copier runs this in the project root, in the `before` stage of `copier update` (see `_migrations` in copier.yml),
before the merge. It lives in the template repo's `migrations/` folder, outside `template/`, so it is never shipped
into a project. Standard library only; the grammar must stay 3.9-compatible because migrations run under the
user's interpreter during `copier update`.

    python3 migrations/docs_layout.py <project-root>

What it does, and what it leaves alone:
- moves each tracked file under docs/{explanation,how-to,reference,tutorials}/ to docs/dev/... with `git mv` (staged,
  because Copier snapshots the index after this stage); an untracked file that git does not ignore is moved and staged;
- leaves ignored files where they are (.DS_Store, Thumbs.db, editor swap files, build output);
- skips the files the v0.2.0 template shipped (OWNED): the merge delivers the new copy at the new path;
- skips generated files (banner "GENERATED by tools/"): the sync tools rebuild them after the update;
- never overwrites: if the target exists, the old file stays and a message goes to stderr;
- rewrites the inline relative Markdown links inside the moved files (a link into a moved folder gains `dev/`, then
  every relative link is recomputed from the new location); absolute URLs, `#anchors` and `/absolute` paths are
  untouched; links written with a title or as a reference definition are left alone;
- prints one `migrate: old -> new` line per moved file, so a second run prints nothing.

Known limits: links from files that stay where they are (your own ADRs, README.md, AGENTS.md) to a moved doc are not
rewritten, and neither are links written with a title or as a reference definition. `python3 tools/check.py` reports
each as `broken-link`.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

MOVED = ("explanation", "how-to", "reference", "tutorials")
GENERATED_BANNER = "GENERATED by tools/"
# The 19 files v0.2.0 shipped in those folders, relative to docs/. The new template ships its own copy at the new path.
OWNED = frozenset("""
    explanation/README.md explanation/context-budget.md explanation/design-rationale.md
    explanation/ownership-and-handoffs.md
    how-to/README.md how-to/add-a-role.md how-to/add-a-skill.md how-to/bootstrap-from-template.md
    how-to/cut-a-module.md how-to/update-from-template.md how-to/use-with-other-agents.md how-to/write-an-adr.md
    reference/README.md reference/commands.md reference/front-matter.md reference/glossary.md
    reference/naming-conventions.md
    tutorials/README.md tutorials/first-work-item.md
""".split())
LINK_RE = re.compile(r"(\]\()([^)\s]+)(\))")
FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
SCHEME_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9+.-]*:")


def is_generated(path: Path) -> bool:
    try:
        return GENERATED_BANNER in path.read_bytes()[:300].decode("utf-8", errors="ignore")
    except OSError:
        return False


def git(root: Path, *args: str) -> None:
    r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"migrate: git {' '.join(args)} failed: {r.stderr.strip()}")


def git_paths(root: Path, *args: str) -> "set[str]":
    """Paths git lists, one per NUL byte. `-z` keeps every name byte-for-byte, without quoting."""
    r = subprocess.run(["git", "-C", str(root), *args], capture_output=True)
    if r.returncode != 0:
        raise SystemExit(f"migrate: git {' '.join(args)} failed: {r.stderr.decode('utf-8', 'replace').strip()}")
    return {os.fsdecode(name) for name in r.stdout.split(b"\0") if name}


def retarget_line(line: str, old_file: Path, new_file: Path) -> str:
    def fix(m: "re.Match[str]") -> str:
        target = m.group(2)
        if SCHEME_RE.match(target) or target.startswith(("#", "/")):
            return m.group(0)
        path, sep, fragment = target.partition("#")
        if not path:
            return m.group(0)
        resolved = Path(os.path.normpath(old_file.parent / path))
        if len(resolved.parts) > 2 and resolved.parts[0] == "docs" and resolved.parts[1] in MOVED:
            resolved = Path("docs", "dev", *resolved.parts[1:])  # the target moves too, shipped or not
        new = os.path.relpath(resolved, new_file.parent).replace(os.sep, "/")
        return f"{m.group(1)}{new}{sep}{fragment}{m.group(3)}"
    return LINK_RE.sub(fix, line)


def retarget(text: str, old_file: Path, new_file: Path) -> str:
    out, fence = [], ""
    for line in text.splitlines(keepends=True):
        m = FENCE_RE.match(line)
        if m:
            marker, rest = m.group(1), m.group(2)
            if not fence:
                fence = marker
            elif marker[0] == fence[0] and len(marker) >= len(fence) and not rest.strip():
                fence = ""
            out.append(line)
        elif fence:
            out.append(line)
        else:
            out.append(retarget_line(line, old_file, new_file))
    return "".join(out)


def plan_moves(root: Path) -> "dict[Path, Path]":
    docs = root / "docs"
    visible = git_paths(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    moves: "dict[Path, Path]" = {}
    for folder in MOVED:
        base = docs / folder
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            if not path.is_file() or path.is_symlink():
                continue
            old = path.relative_to(root)
            if old.as_posix() not in visible:
                continue  # ignored: .DS_Store, Thumbs.db, editor swaps, build output
            if path.relative_to(docs).as_posix() in OWNED or is_generated(path):
                continue
            new = Path("docs", "dev", *path.relative_to(docs).parts)
            if (root / new).exists():
                print(f"migrate: {new.as_posix()} already exists, left {old.as_posix()} where it is", file=sys.stderr)
                continue
            moves[old] = new
    return moves


def main(argv: "list[str]") -> int:
    if len(argv) != 2:
        print(__doc__.split("\n\n")[0] + "\nusage: docs_layout.py <project-root>", file=sys.stderr)
        return 2
    root = Path(argv[1]).resolve()
    tracked = git_paths(root, "ls-files", "-z", "--cached")
    for old, new in plan_moves(root).items():
        (root / new).parent.mkdir(parents=True, exist_ok=True)
        raw = (root / old).read_bytes()
        if old.as_posix() in tracked:
            git(root, "mv", old.as_posix(), new.as_posix())
        else:  # untracked but not ignored: move it and stage it like the tracked files
            (root / old).replace(root / new)
            git(root, "add", new.as_posix())
        if old.suffix.lower() == ".md":
            try:
                text = raw.decode("utf-8")
            except UnicodeDecodeError:
                text = None
            fixed = retarget(text, old, new) if text is not None else None
            if fixed is not None and fixed != text:
                (root / new).write_bytes(fixed.encode("utf-8"))
                git(root, "add", new.as_posix())
        print(f"migrate: {old.as_posix()} -> {new.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
